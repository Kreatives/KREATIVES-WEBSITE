export function getProjectEn(slug: string): Project | undefined {
  return projectenEn.find((p) => p.slug === slug);
}

export function getRelatedProjectsEn(slug: string): Project[] {
  const project = getProjectEn(slug);
  if (!project?.related) return [];
  return project.related
    .map((s) => getProjectEn(s))
    .filter((p): p is Project => Boolean(p));
}
